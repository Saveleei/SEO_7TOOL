export function getCategoryExpertProfile(slug) {
  const profile = categoryExpertProfiles[slug] ?? fallbackProfile;
  const familyProfile = getCategoryFamilyShortcuts(slug);
  if (!familyProfile) return profile;
  const structuralShortcuts = (profile.assortmentShortcuts ?? []).filter((shortcut) => shortcut.segment || shortcut.productType);
  return {
    ...profile,
    assortmentPrompt:familyProfile.assortmentPrompt,
    assortmentShortcuts:[...structuralShortcuts, ...familyProfile.assortmentShortcuts],
  };
}

export function getCategoryExpertProfileSlugs() {
  return Object.keys(categoryExpertProfiles);
}

export function getCategoryFacetKeywords(slug) {
  return getCategoryExpertProfile(slug).facetKeywords;
}

export function selectCategoryFacets(slug, facets, limit = 3, priorityOverride) {
  const profile = getCategoryExpertProfile(slug);
  const selected = [];
  const priorities = Array.isArray(priorityOverride) && priorityOverride.length > 0 ? priorityOverride : profile.promotedFacetKeywords;
  for (const priority of priorities) {
    const facet = facets.find((candidate) => !selected.includes(candidate) && facetMatches(candidate, priority));
    if (facet) selected.push(facet);
    if (selected.length === limit) return selected;
  }
  for (const facet of facets) {
    if (facet.keyword && !selected.includes(facet)) selected.push(facet);
    if (selected.length === limit) break;
  }
  return selected;
}

export function selectCategoryAssistantFacets(slug, facets) {
  const profile = getCategoryExpertProfile(slug);
  if (profile.selectionMode === "engineer") return [];
  return selectCategoryFacets(slug, facets, profile.selectorFacetLimit ?? 3);
}

function facetMatches(facet, priority) {
  if (priority === "brand") return facet.key === "brand";
  if (!facet.keyword) return false;
  const value = normalize(`${facet.keyword} ${facet.label ?? ""}`);
  const expected = normalize(priority);
  return value.includes(expected);
}

function normalize(value) {
  return value.toLocaleLowerCase("ru-RU").replace(/ё/g, "е").replace(/[^a-zа-я0-9]+/giu, " ").trim();
}
