export function contentForCategory(slug: string, fallbackTitle: string): CategoryContent {
  const generated = (categorySeo as Record<string, Omit<CategoryContent, "selectionTitle" | "selectionFields">>)[slug];
  const existing = categoryContent[slug];
  const selection = existing ?? additionalSelection[slug];
  if (generated) {
    return {
      ...generated,
      selectionTitle: selection?.selectionTitle ?? `Подбор: ${fallbackTitle}`,
      selectionFields: selection?.selectionFields ?? [],
    };
  }
  if (existing) {
    return {
      ...existing,
      faq: [],
      primaryQuery: fallbackTitle.toLowerCase(),
      productPurpose: `применения в разделе «${fallbackTitle}»`,
    };
  }
  return {
    h1: fallbackTitle,
    intro: `Каталог ${fallbackTitle.toLowerCase()} с актуальными вариантами, ценами и статусами поставки.`,
    metaTitle: `${fallbackTitle} — купить`,
    metaDescription: `${fallbackTitle}: характеристики, актуальные цены с НДС, доступность для заказа, инженерный подбор и доставка по России.`,
    keywords: [fallbackTitle.toLowerCase(), `${fallbackTitle.toLowerCase()} купить`],
    primaryQuery: fallbackTitle.toLowerCase(),
    productPurpose: `применения в разделе «${fallbackTitle}»`,
    seoTitle: `Подбор: ${fallbackTitle}`,
    seoText: ["Сравните модели по характеристикам и доступности. Для нестандартной задачи отправьте параметры инженеру."],
    faq: [],
    selectionTitle: `Подбор: ${fallbackTitle}`,
    selectionFields: [],
  };
}
